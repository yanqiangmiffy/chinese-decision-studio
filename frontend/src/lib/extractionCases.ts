import { TYPE_SETS, type TypeSpec } from "./extractionTypes";

// 抽取案例：每条是一段文本 + 一组类型（名称 + 说明）。
// 类型默认取自 TYPE_SETS（说明和模型训练时一致）；domain = custom 的案例自己写类型，那是训练里没见过的类型。
// 文本都是为演示编写的虚构内容；expect 是人工写的参考答案，只在案例馆里“对照参考答案”时用，不参与任何评分。
// 实测（chinese-decision v3，0.8B 联合训练）：
//  · 说明越接近训练写法召回越高：地址要素用训练说明抽出 7 个，只给类型名只抽出 3 个；
//  · MSRA 的标注习惯会把“中法关系”里的“中”“法”各标成地名，这是标注规范，不是模型出错；
//  · 自定义类型能抽出时间、地点、编号这类“形状明确”的内容，抽象类型（会议主题、职责）基本抽不出来。

export interface ExtractCase {
  id: string;
  domain: string;
  title: string;
  text: string;
  /** 取自 TYPE_SETS 的哪一组 */
  set?: string;
  /** 自己写的类型（domain = custom）；有 set 时忽略 */
  types?: TypeSpec[];
  /** 参考答案：[类型名, 原文片段] */
  expect?: [string, string][];
  note?: string;
}

