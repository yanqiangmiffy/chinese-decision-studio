/** 案例要发给模型的类型：优先取 TYPE_SETS 里的训练写法。 */
export function typesOf(c: ExtractCase): TypeSpec[] {
  return c.set ? TYPE_SETS[c.set].types : (c.types ?? []);
}

// ---------------------------------------------------------------- 页面之间传递一个抽取请求（“在实验台打开”）
const HANDOFF = "ds-extract-handoff";
export function handoffExtract(payload: { text: string; types: TypeSpec[] }) {
  sessionStorage.setItem(HANDOFF, JSON.stringify(payload));
}
export function hasExtractHandoff(): boolean {
  return sessionStorage.getItem(HANDOFF) !== null;
}
export function takeExtractHandoff(): { text: string; types: TypeSpec[] } | null {
  const raw = sessionStorage.getItem(HANDOFF);
  if (!raw) return null;
  sessionStorage.removeItem(HANDOFF);
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------- 与参考答案对照
export interface ReferenceCheck {
  hit: [string, string][];
  /** 类型对、文字有包含关系（边界不一致） */
  near: [string, string][];
  missed: [string, string][];
  /** 模型多抽的：和任何参考答案都不对应 */
  extra: [string, string][];
}

const squash = (s: string) => s.replace(/\s+/g, "");
const overlaps = (a: string, b: string) => squash(a).includes(squash(b)) || squash(b).includes(squash(a));

export function checkAgainstReference(entities: { label: string; text: string }[], expect: [string, string][]): ReferenceCheck {
  const found = entities.map((e) => [e.label, e.text] as [string, string]);
  const exact = (r: [string, string]) => found.some((f) => f[0] === r[0] && squash(f[1]) === squash(r[1]));
  const loose = (r: [string, string]) => found.some((f) => f[0] === r[0] && overlaps(f[1], r[1]));
  const hit = expect.filter(exact);
  const near = expect.filter((r) => !exact(r) && loose(r));
  const missed = expect.filter((r) => !exact(r) && !loose(r));
  const extra = found.filter((f) => !expect.some((r) => f[0] === r[0] && overlaps(f[1], r[1])));
  return { hit, near, missed, extra };
}
