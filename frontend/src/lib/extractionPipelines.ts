// 训练时有几个关系名读起来不通顺，改写成这样的类型名（与 decision/data/ie/relation.py 的 PHRASES 一致）
const PHRASES: Record<string, string> = { 获奖: "{s}获得的奖项", 饰演: "{s}饰演的角色", 配音: "{s}配音的角色", 改编自: "{s}的改编来源" };

export function relationTypeName(subject: string, relation: string): string {
  return (PHRASES[relation] ?? "{s}的" + relation).replace("{s}", subject);
}

