"""生成内置评测集的 JSONL。改用例改这里，然后运行：python data/suites/build.py

每个评测集是一组同构的用例：同样的问题定义 + 不同的上下文和标准答案。
标签（meta.tag）用来在报告里按类别拆指标。
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def write(slug, questions, rows, make_state=lambda s: s):
    lines = []
    for i, (state, gold, tag) in enumerate(rows, start=1):
        names = list(questions)
        gold = gold if isinstance(gold, tuple) else (gold,)
        lines.append(json.dumps({
            "id": f"{slug}-{i:02d}",
            "state": make_state(state),
            "questions": questions,
            "gold": dict(zip(names, gold, strict=True)),
            "meta": {"tag": tag},
        }, ensure_ascii=False))
    (HERE / f"{slug}.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{slug}: {len(lines)} cases")


